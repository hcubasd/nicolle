"""Measure one shared opaque-pixel rectangle across each sheet's 16 frames.
Requires Pillow. Regenerate after changing the source PNGs; never rescales pixels.
"""
from pathlib import Path
from PIL import Image
import json
root=Path(__file__).resolve().parents[1]
paths=sorted((root/'public/grafos/animals').glob('*.png'))+[root/'public/grafos/gunner02.png']
result={}
for path in paths:
    image=Image.open(path).convert('RGBA')
    assert image.width%4==0 and image.height%4==0
    width,height=image.width//4,image.height//4
    boxes=[image.crop((x*width,y*height,(x+1)*width,(y+1)*height)).getchannel('A').getbbox() for y in range(4) for x in range(4)]
    boxes=[box for box in boxes if box]
    result['human' if path.stem=='gunner02' else path.stem]={'left':min(b[0] for b in boxes),'top':min(b[1] for b in boxes),'right':max(b[2] for b in boxes),'bottom':max(b[3] for b in boxes)}
(root/'src/rescue/sprite-bounds.ts').write_text('// Generated by scripts/measure-sprites.py; coordinates are native pixels.\nexport const spriteBounds = '+json.dumps(result,indent=2)+' as const;\n')
